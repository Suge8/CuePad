import CoreGraphics

/// 开屏的字标：「Cue」「Pad」叠两行，字形取自 Geist Pixel Square（Vercel，SIL OFL 1.1）——按它自己的像素格（38/1000 em）取下来，每笔往右下加粗一格。
/// 一格就是开屏点阵屏的一格（`OpeningLight.cell`）：字占的格整格亮，其余格是点，同一张网。
/// iOS 的启动图（`LaunchStage`）是米白那一版连着 Cue 导出的（`-CuePadLaunchArt`）：改了字形、格子或摆法要重导，不然启动屏与开屏第一帧接不上。
nonisolated enum CueWordmark {
    private static let rows = [
        "....#########................................",
        "..##############.............................",
        "..##############.............................",
        ".#####......#####............................",
        ".####........####............................",
        "####..........###..###.....###....#########..",
        "####..........###..###.....###...###########.",
        "###...........###..###.....###...###########.",
        "###................###.....###..#####...#####",
        "###................###.....###..####.....####",
        "###................###.....###..####.....####",
        "###................###.....###..#############",
        "####..........###..###.....###..#############",
        "####..........###..###.....###..#############",
        ".####........####..###.....###..####.........",
        ".#####......#####..####...####..#####....####",
        "..#####....#####...#####.#####...#####..#####",
        "..##############...###########...############",
        "...############.....##########....##########.",
        ".....#######.........#####.###.....#######...",
        ".............................................",
        ".............................................",
        ".###########.............................###.",
        ".#############...........................###.",
        ".#############...........................###.",
        ".###......#####..........................###.",
        ".###.......####..........................###.",
        ".###........###....########......###########.",
        ".###.......####..###########....############.",
        ".###......#####..############...############.",
        ".####....#####...####....####..#####....####.",
        ".#############...###.....####..####.....####.",
        ".############...........#####..###.......###.",
        ".##########........##########..###.......###.",
        ".###.............############..###.......###.",
        ".###.............############..###.......###.",
        ".###.............####.....###..####.....####.",
        ".###.............###.....####..#####....####.",
        ".###.............####...######..#####..#####.",
        ".###.............#############..############.",
        ".###..............############...###########.",
        ".###...............######..###....######.###.",
    ]
    static let size = SIMD2(rows[0].count, rows.count)
    static let cells: Set<SIMD2<Int>> = Set(rows.enumerated().flatMap { row, line in
        line.enumerated().compactMap { column, mark in mark == "#" ? SIMD2(column, row) : nil }
    })
    /// Cue 站在「ue」顶上：它的中线在第几列，脚踩在第几行的上沿。
    static let perch = SIMD2(32, 5)

    /// 一格一个像素，字格是 `paint` 给的颜色，其余透明（上下按屏幕的上下：第 0 行在最上）。
    static func image(_ paint: (SIMD2<Int>) -> OpeningDoor.Pixel) -> CGImage {
        var pixels = [OpeningDoor.Pixel](repeating: 0, count: size.x * size.y)
        for cell in cells { pixels[cell.y * size.x + cell.x] = paint(cell) }
        return OpeningDoor.image(pixels, size: size)
    }
}
