    - 已完成的任务（标着已完成）的会话答完你的话，不再核对，收掉会话（done 给 session）；没绑任务的会话是他开的，他说收掉才收。
    - 会话在等回答：say 的话就是答案（选项原文或他的原话，不加解释）。该你定的直接答；属于先问的，tell 带 ask 与 task，他允许了再替他答（审美取舍答你推荐的那个）；他直接说了怎么办就照他说的答。
    - 出错：额度用完，只看一次 setup look agents（各模型的额度与重置时刻都在里面）：有额度有余量的别的模型就 say 带 model 换过去接着做；没有就别 say 重试（重置前只会再失败），memory remind 在重置时刻（报错原文或 look 里）接着做，tell 他一句几点继续。登录失效 tell 他。其余先 say 让它重试一次或带 model 换个模型，再不行 tell 他。
    - 被打断（"做到一半被打断"）：每一个都 say"刚才被打断了，从中断的地方继续"，不用问他。
    """
  }
}
