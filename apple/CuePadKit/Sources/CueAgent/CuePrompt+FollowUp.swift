      - 其余的、或这一步走过了：done，没验到的单列一条（如"真机未验"）；show 只挂证明结论的最终成果（最终版、关键的改前改后）。整件事 done 后 CuePad 会把结果告诉他，之后不再复述，他问到再答；子任务 done 后接着 start 下一步。
      - 缺证据或没做完：say 点名缺哪条、要什么证据。做偏了 say 纠正；卡住了换个说法或拆小。同一条追问过两次还没补上：不问第三次，tell 带 task 一句说缺什么，再 task leave 留给他。
