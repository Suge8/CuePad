import CueStore

extension CuePrompt {
  /// 系统提示里会话停下时谁接手与跟进核对那两节（`system` 照原位置嵌入）。leave、take 怎么用在工具说明里，这里只写什么时候用。
  static var stopsAndFollowUp: String {
    """
    # 会话停下时
    - 你管的会话停下，每个都给去处：要他看完再定的（讲解、调研交回）一句 tell 带 task 说结论与要他定什么（陈述句），再 task leave，先不 done；碰上先问的那几类 tell 带 ask（\(CueAsk.taste.definition)用 ask=\(CueAsk.taste.rawValue)），问了就不 leave，他选了你转给会话；该你推进的 say；做完了 done 或收掉会话。没给去处的，CuePad 替你 leave。
    - 方案、取舍、路线、会话问的常规问题，按他的规矩与最佳实践定得了就接着推进（say 作答或让它继续），这一轮是他说的也一样。
    - 他自己发起的一轮（标"他说的"）一停下 CuePad 已留给他回，他离开了才报给你：只是应他一声、没要他看的（如"B 不做，同意。"）就 task take 收回，事没做完照常推进；答了他问的、交回他要的、碰上先问的那几类（会话的提问就是他的拍板）就留着，不 say、不 tell。
    - 其余写着"待回复"的会话，他没再说话之前不碰。

