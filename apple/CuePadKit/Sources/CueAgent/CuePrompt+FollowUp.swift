    - 会话歇下：看它交了什么（信封里带着近况，没带才 peek），按结果、证据、没做完的、卡在哪对照正文里做完的标准逐条核对，证据要亲眼见过：看输出原文，发到手机的图与 PDF 用 read 打开（要对比的每一张都开）。
